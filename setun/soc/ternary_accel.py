"""LiteX AutoCSR + Wishbone Burst DMA wrapper for multi-row TernaryTile + Requantize."""

from __future__ import annotations

import re
from pathlib import Path

from litex.soc.integration import export
from litex.soc.interconnect import wishbone
from litex.soc.interconnect.csr import AutoCSR, CSRField, CSRStatus, CSRStorage
from migen import Array, Case, Cat, If, Memory, Module, Mux, ResetInserter, Signal
from migen.genlib.fifo import SyncFIFOBuffered

from setun.accelerators.requantize import Requantize
from setun.accelerators.tile import TernaryTile
from setun.accelerators.unpacker import WeightUnpacker

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_CSR_JSON = REPO_ROOT / "reports" / "csr.json"
DEFAULT_CSR_HEADER = REPO_ROOT / "reports" / "csr.h"

_DETERMINISTIC_BANNER = (
    "//--------------------------------------------------------------------------------\n"
    "// Auto-generated by LiteX for Setun Simulated SoC (deterministic CSR map)\n"
    "//--------------------------------------------------------------------------------"
)

_CTI_CLASSIC = 0b000
_CTI_BURST_INC = 0b010
_CTI_BURST_END = 0b111

_DMA_IDLE = 0
_DMA_ACT_BURST = 1
_DMA_STREAM_ARB = 2
_DMA_SCALE_BURST = 3
_DMA_TRIT_BURST = 4
_DMA_WAIT_COMPUTE = 5
_DMA_OUT_WRITE_WB = 6


class TernaryAccel(Module, AutoCSR):
    """Multi-row streaming ternary GEMV LiteX CSR + Wishbone burst DMA peripheral (Tasks 3.1/3.2).

    Composes maintainer-owned RTL cores without modifying `setun/accelerators/`:
      `dma_wb` / stream -> `WeightUnpacker` -> `(R-1)` BRAMs -> `TernaryTile` -> `Requantize`
    """

    def __init__(
        self,
        rows: int = 4,
        lanes: int = 64,
        group_size: int = 128,
        beat_bits: int = 256,
        act_bits: int = 8,
        acc_bits: int = 48,
        max_k: int = 2048,
        max_rows: int = 2048,
    ) -> None:
        if rows < 1:
            raise ValueError(f"soc.TernaryAccel: rows must be >= 1, got {rows}.")
        if act_bits != 8:
            raise ValueError(
                f"soc.TernaryAccel: expected act_bits == 8 for CSR word staging, got {act_bits}."
            )
        if lanes < 4 or lanes % 4 != 0 or (lanes & (lanes - 1)) != 0:
            raise ValueError(
                f"soc.TernaryAccel: expected lanes to be a power-of-2 multiple of 4, got {lanes}."
            )
        if max_k < group_size or max_k % group_size != 0:
            raise ValueError(
                f"soc.TernaryAccel: max_k ({max_k}) must be a positive multiple of "
                f"group_size ({group_size})."
            )
        if max_rows < 1:
            raise ValueError(f"soc.TernaryAccel: max_rows must be >= 1, got {max_rows}.")

        self.rows = rows
        self.lanes = lanes
        self.group_size = group_size
        self.beat_bits = beat_bits
        self.act_bits = act_bits
        self.acc_bits = acc_bits
        self.max_k = max_k
        self.max_rows = max_rows
        self.max_beats = max_k // lanes
        self.words_per_slice = lanes // 4
        self.total_act_words = self.max_beats * self.words_per_slice
        self.dma_capable = (beat_bits >= 32) and (beat_bits % 32 == 0)
        self.words_per_beat = max(beat_bits // 32, 1)

        # Instantiate maintainer-owned RTL cores and unify onto SoCCore's sys clock domain
        unpacker = WeightUnpacker(beat_bits=beat_bits, lanes=lanes, group_size=group_size)
        tile = TernaryTile(
            rows=rows,
            lanes=lanes,
            group_size=group_size,
            act_bits=act_bits,
            acc_bits=acc_bits,
            max_k=max_k,
        )
        requantize = Requantize(in_bits=acc_bits, out_bits=8)
        for sub in (unpacker, tile, requantize):
            if hasattr(sub, "_fragment"):
                sub._fragment.clock_domains.clear()
        self.submodules.unpacker = unpacker
        self.submodules.tile = tile
        self.submodules.requantize = requantize

        # External stream push ports (used when weight_addr == 0 and scale_addr == 0)
        self.trit_data = Signal(beat_bits, name="ext_trit_data")
        self.trit_last = Signal(name="ext_trit_last")
        self.trit_valid = Signal(name="ext_trit_valid")
        self.trit_ready = Signal(name="ext_trit_ready")
        self.scale_data = Signal(16, name="ext_scale_data")
        self.scale_valid = Signal(name="ext_scale_valid")
        self.scale_ready = Signal(name="ext_scale_ready")

        # 32-bit Wishbone burst DMA master interface (Tasks 3.2 & 3.2b)
        self.dma_wb = wishbone.Interface(data_width=32, adr_width=30, bursting=True)

        # -------------------------------------------------------------------
        # CSR Register Map (#0..#9 locked at Task 3.1a offsets +0x00..+0x24)
        # -------------------------------------------------------------------
        self.ctrl = CSRStorage(
            32,
            name="ctrl",
            description="Accelerator stream enable, reset, launch, and requantize control",
            fields=[
                CSRField("enable", size=1, offset=0, reset=1, description="Enable stream ready"),
                CSRField("clear", size=1, offset=1, pulse=True, description="Clear state/flags"),
                CSRField("start", size=1, offset=2, pulse=True, description="Validate & start"),
                CSRField("req_enable", size=1, offset=3, reset=0, description="Enable Requantize"),
                CSRField("req_sym", size=1, offset=4, reset=0, description="Symmetric int8 clamp"),
            ],
        )
        self.cfg = CSRStorage(
            32,
            name="cfg",
            description="Per-layer shift exponent and target output row count",
            fields=[
                CSRField("shift", size=6, offset=0, reset=0, description="Tile shift in [0, 30]"),
                CSRField("num_rows", size=16, offset=8, reset=1, description="Target rows N"),
            ],
        )
        info_reset = (lanes & 0xFF) | ((group_size & 0xFFF) << 8) | ((beat_bits & 0xFFF) << 20)
        self.info = CSRStatus(
            32,
            reset=info_reset,
            name="info",
            description="Synthesized datapath geometry (lanes, group_size, beat_bits)",
            fields=[
                CSRField("lanes", size=8, offset=0, reset=lanes),
                CSRField("group_size", size=12, offset=8, reset=group_size),
                CSRField("beat_bits", size=12, offset=20, reset=beat_bits),
            ],
        )
        self.status = CSRStatus(
            32,
            name="status",
            description="Pipeline readiness, sticky error/saturation flags, and row progress",
            fields=[
                CSRField("busy", size=1, offset=0, description="1 while GEMV active and error==0"),
                CSRField("done", size=1, offset=1, description="1 when rows_completed >= num_rows"),
                CSRField("trit_ready", size=1, offset=2, description="Live unpacker.trit_ready"),
                CSRField("scale_ready", size=1, offset=3, description="Live unpacker.scale_ready"),
                CSRField("error", size=1, offset=4, description="Sticky illegal-parameter flag"),
                CSRField("req_saturated", size=1, offset=5, description="Sticky Requantize clip"),
                CSRField("err_code", size=4, offset=8, description="Sticky 4-bit error bitmask"),
                CSRField("rows_completed", size=16, offset=16, description="Completed row count"),
            ],
        )
        self.act_word_idx = CSRStorage(
            16,
            name="act_word_idx",
            description="32-bit word write pointer into quantized int8 activation BRAM",
        )
        self.act_word_data = CSRStorage(
            32,
            name="act_word_data",
            description="Write 4 packed int8 activations (LE) to BRAM and auto-increment pointer",
        )
        self.result_lo = CSRStatus(
            32,
            name="result_lo",
            description="Lower 32 bits of most recent row output",
        )
        self.result_hi = CSRStatus(
            32,
            name="result_hi",
            description="Sign-extended upper bits [47:32] of most recent row output",
        )
        self.out_row_idx = CSRStorage(
            16,
            name="out_row_idx",
            description="Row index selector driving synchronous read port of output BRAM",
        )
        self.out_row_data = CSRStatus(
            32,
            name="out_row_data",
            description="Signed int32 result from output BRAM for row out_row_idx",
        )

        # -------------------------------------------------------------------
        # Phase-3 CSRs (#10..#21 appended strictly after +0x24)
        # -------------------------------------------------------------------
        tile_info_rst = (rows & 0xFF) | ((lanes & 0xFF) << 8) | ((group_size & 0xFFFF) << 16)
        self.tile_info = CSRStatus(
            32,
            reset=tile_info_rst,
            name="tile_info",
            description="Multi-row tile geometry (rows, lanes, hw_group_size)",
            fields=[
                CSRField("rows", size=8, offset=0, reset=rows),
                CSRField("lanes", size=8, offset=8, reset=lanes),
                CSRField("hw_group_size", size=16, offset=16, reset=group_size),
            ],
        )
        buf_caps_rst = (max_k & 0xFFFF) | ((max_rows & 0xFFFF) << 16)
        self.buf_caps = CSRStatus(
            32,
            reset=buf_caps_rst,
            name="buf_caps",
            description="Synthesized scratchpad capacities (max_k, max_rows up to 65535)",
            fields=[
                CSRField("max_k", size=16, offset=0, reset=max_k),
                CSRField("max_rows", size=16, offset=16, reset=max_rows),
            ],
        )
        dim_k_rst = (group_size & 0xFFFF) | ((group_size & 0xFFFF) << 16)
        self.dim_k = CSRStorage(
            32,
            reset=dim_k_rst,
            name="dim_k",
            description="Layer K dimension and expected group_size validated on ctrl.start",
            fields=[
                CSRField("k_cols", size=16, offset=0, reset=group_size),
                CSRField("group_size", size=16, offset=16, reset=group_size),
            ],
        )
        self.weight_addr = CSRStorage(32, name="weight_addr", description="4B-aligned weight ptr")
        self.scale_addr = CSRStorage(32, name="scale_addr", description="4B-aligned scale ptr")
        self.act_addr = CSRStorage(32, name="act_addr", description="4B-aligned activation ptr")
        self.out_addr = CSRStorage(32, name="out_addr", description="4B-aligned output ptr")
        self.act_scale = CSRStorage(32, name="act_scale", description="Host FP32 act_scale bits")
        self.req_cfg = CSRStorage(
            32,
            reset=1,
            name="req_cfg",
            description="Requantize unsigned scale_u16 and right-shift exponent",
            fields=[
                CSRField("scale_u16", size=16, offset=0, reset=1),
                CSRField("shift", size=6, offset=16, reset=0),
            ],
        )
        self.perf_cycles = CSRStatus(32, name="perf_cycles", description="Busy cycles in run")
        self.perf_bus_beats = CSRStatus(32, name="perf_bus_beats", description="Accepted beats")
        self.perf_sat_rows = CSRStatus(32, name="perf_sat_rows", description="Clipped int8 rows")

        self.comb += [
            self.info.fields.lanes.eq(lanes),
            self.info.fields.group_size.eq(group_size),
            self.info.fields.beat_bits.eq(beat_bits),
            self.tile_info.fields.rows.eq(rows),
            self.tile_info.fields.lanes.eq(lanes),
            self.tile_info.fields.hw_group_size.eq(group_size),
            self.buf_caps.fields.max_k.eq(max_k),
            self.buf_caps.fields.max_rows.eq(max_rows),
        ]

        # -------------------------------------------------------------------
        # Synchronous BRAM Scratchpads (async_read=False -> RAMB18E1 / DP16KD)
        # -------------------------------------------------------------------
        act_mem_depth = max(self.total_act_words, 2)
        act_scratch_mem = Memory(width=32, depth=act_mem_depth)
        act_wr_port = act_scratch_mem.get_port(write_capable=True)
        act_rd_port = act_scratch_mem.get_port(async_read=False)
        self.specials += act_scratch_mem, act_wr_port, act_rd_port

        out_mem_depth = max(self.max_rows, 2)
        out_scratch_mem = Memory(width=32, depth=out_mem_depth)
        out_wr_port = out_scratch_mem.get_port(write_capable=True)
        out_rd_port = out_scratch_mem.get_port(async_read=False)
        self.specials += out_scratch_mem, out_wr_port, out_rd_port

        # Dedicated 32-bit packed int8 staging BRAM for req_enable == 1 (Task 3.2b)
        out_pack_depth = max((self.max_rows + 3) // 4, 128)
        out_pack_mem = Memory(width=32, depth=out_pack_depth)
        out_pack_wr = out_pack_mem.get_port(write_capable=True)
        out_pack_rd = out_pack_mem.get_port(async_read=False)
        self.specials += out_pack_mem, out_pack_wr, out_pack_rd

        stripe_mem_depth = max(self.max_beats, 128) if rows > 1 else 2
        stripe_entry_bits = 2 * lanes + 16
        sw_ports = []
        sr_ports = []
        for _b in range(rows - 1):
            smem = Memory(width=stripe_entry_bits, depth=stripe_mem_depth)
            sw_p = smem.get_port(write_capable=True)
            sr_p = smem.get_port(async_read=False, has_re=True)
            self.specials += smem, sw_p, sr_p
            sw_ports.append(sw_p)
            sr_ports.append(sr_p)

        # -------------------------------------------------------------------
        # Control, Parameter Validation, and DMA / Stream FIFOs
        # -------------------------------------------------------------------
        enable_sig = self.ctrl.fields.enable
        clear_sig = self.ctrl.fields.clear
        start_sig = self.ctrl.fields.start
        req_en_sig = self.ctrl.fields.req_enable
        req_sym_sig = self.ctrl.fields.req_sym
        shift_sig = self.cfg.fields.shift
        num_rows_sig = self.cfg.fields.num_rows
        k_cols_sig = self.dim_k.fields.k_cols
        g_cfg_sig = self.dim_k.fields.group_size

        err_k = Signal(name="err_k")
        err_n = Signal(name="err_n")
        err_g = Signal(name="err_g")
        err_align = Signal(name="err_align")
        partial_ptr_err = Signal(name="partial_ptr_err")
        dma_width_err = Signal(name="dma_width_err")
        start_err_mask = Signal(4, name="start_err_mask")

        self.comb += [
            err_k.eq((k_cols_sig == 0) | (k_cols_sig > max_k)),
            err_n.eq((num_rows_sig == 0) | (num_rows_sig > max_rows)),
            err_g.eq(g_cfg_sig != group_size),
            partial_ptr_err.eq((self.weight_addr.storage != 0) ^ (self.scale_addr.storage != 0)),
            dma_width_err.eq(
                0
                if self.dma_capable
                else (
                    (self.weight_addr.storage != 0)
                    | (self.scale_addr.storage != 0)
                    | (self.act_addr.storage != 0)
                    | (self.out_addr.storage != 0)
                )
            ),
            err_align.eq(
                (self.weight_addr.storage[0:2] != 0)
                | (self.scale_addr.storage[0:2] != 0)
                | (self.act_addr.storage[0:2] != 0)
                | (self.out_addr.storage[0:2] != 0)
                | partial_ptr_err
                | dma_width_err
            ),
            start_err_mask.eq(Cat(err_k, err_n, err_g, err_align)),
        ]

        err_sticky = Signal(name="err_sticky")
        err_code_reg = Signal(4, name="err_code_reg")
        req_sat_sticky = Signal(name="req_sat_sticky")
        rows_done = Signal(16, name="rows_done")
        last_res = Signal((acc_bits, True), name="last_res")
        perf_cycles_cnt = Signal(32, name="perf_cycles_cnt")
        perf_beats_cnt = Signal(32, name="perf_beats_cnt")
        perf_sat_cnt = Signal(32, name="perf_sat_cnt")

        # Power-of-two shift helpers for zero-divider word counts
        g_shift = group_size.bit_length() - 1
        words_per_group_act = group_size // 4
        wpg_act_shift = words_per_group_act.bit_length() - 1
        wps_shift = self.words_per_slice.bit_length() - 1
        wpg_trit = max(group_size // 16, 1)
        wpg_trit_shift = wpg_trit.bit_length() - 1

        k_plus_pad = Signal(17, name="k_plus_pad")
        n_groups_wire = Signal(17, name="n_groups_wire")
        target_load_words = Signal(17, name="target_load_words")
        trit_w_per_row_wire = Signal(17, name="trit_w_per_row_wire")
        trit_total_words_wire = Signal(32, name="trit_total_words_wire")
        scale_total_u16_wire = Signal(32, name="scale_total_u16_wire")
        scale_total_words_wire = Signal(32, name="scale_total_words_wire")

        self.comb += [
            k_plus_pad.eq(k_cols_sig + (group_size - 1)),
            n_groups_wire.eq(k_plus_pad >> g_shift),
            target_load_words.eq(n_groups_wire << wpg_act_shift),
            trit_w_per_row_wire.eq(n_groups_wire << wpg_trit_shift),
            trit_total_words_wire.eq(num_rows_sig * trit_w_per_row_wire),
            scale_total_u16_wire.eq(num_rows_sig * n_groups_wire),
            scale_total_words_wire.eq((scale_total_u16_wire + 1) >> 1),
        ]

        # DMA Scale & Trit FIFOs (reset cleanly on clear or start)
        max_beats_in_burst = (64 + self.words_per_beat - 1) // self.words_per_beat
        trit_fifo_depth = max_beats_in_burst + 8
        scale_fifo = ResetInserter()(SyncFIFOBuffered(width=32, depth=64))
        trit_fifo = ResetInserter()(SyncFIFOBuffered(width=beat_bits + 1, depth=trit_fifo_depth))
        self.submodules.scale_fifo = scale_fifo
        self.submodules.trit_fifo = trit_fifo
        self.comb += [
            scale_fifo.reset.eq(clear_sig | start_sig),
            trit_fifo.reset.eq(clear_sig | start_sig),
        ]

        # DMA Engine State & Registers
        dma_state = Signal(3, name="dma_state")
        weight_dma_active = Signal(name="weight_dma_active")
        act_dma_active = Signal(name="act_dma_active")
        out_dma_active = Signal(name="out_dma_active")
        out_dma_done = Signal(name="out_dma_done")
        any_dma_run = Signal(name="any_dma_run")

        cur_act_waddr = Signal(30, name="cur_act_waddr")
        cur_scale_waddr = Signal(30, name="cur_scale_waddr")
        cur_trit_waddr = Signal(30, name="cur_trit_waddr")
        cur_out_waddr = Signal(30, name="cur_out_waddr")

        dma_act_idx = Signal(17, name="dma_act_idx")
        dma_out_idx = Signal(17, name="dma_out_idx")
        burst_rem = Signal(17, name="burst_rem")
        dma_scale_words_rem = Signal(32, name="dma_scale_words_rem")
        dma_trit_words_rem = Signal(32, name="dma_trit_words_rem")
        latched_trit_w_per_row = Signal(17, name="latched_trit_w_per_row")
        latched_scale_u16_total = Signal(32, name="latched_scale_u16_total")
        scale_emitted_cnt = Signal(32, name="scale_emitted_cnt")
        scale_half_idx = Signal(name="scale_half_idx")

        trit_sub_idx = Signal(max=max(self.words_per_beat, 2), name="trit_sub_idx")
        trit_row_word_idx = Signal(17, name="trit_row_word_idx")
        trit_pack_words = Array(
            [Signal(32, name=f"tpack_w_{w}") for w in range(self.words_per_beat)]
        )

        dma_ack = Signal(name="dma_ack")
        self.comb += [
            dma_ack.eq(self.dma_wb.cyc & self.dma_wb.stb & self.dma_wb.ack),
            any_dma_run.eq(weight_dma_active | act_dma_active | out_dma_active),
        ]

        # Output beat count & combinational tail byte-enable strobe (Task 3.2b)
        out_dma_beats_total = Signal(17, name="out_dma_beats_total")
        is_final_out_beat = Signal(name="is_final_out_beat")
        tail_rem_2b = Signal(2, name="tail_rem_2b")
        tail_sel_4b = Signal(4, name="tail_sel_4b")
        out_wb_sel = Signal(4, name="out_wb_sel")

        self.comb += [
            out_dma_beats_total.eq(Mux(req_en_sig, (num_rows_sig + 3) >> 2, num_rows_sig)),
            is_final_out_beat.eq((dma_out_idx + 1) >= out_dma_beats_total),
            tail_rem_2b.eq(num_rows_sig[0:2]),
            Case(
                tail_rem_2b,
                {
                    0: tail_sel_4b.eq(0b1111),
                    1: tail_sel_4b.eq(0b0001),
                    2: tail_sel_4b.eq(0b0011),
                    3: tail_sel_4b.eq(0b0111),
                },
            ),
            out_wb_sel.eq(Mux(req_en_sig & is_final_out_beat, tail_sel_4b, 0xF)),
        ]

        # Wishbone DMA Master Bus Drive
        burst_cti = Mux(burst_rem == 1, _CTI_BURST_END, _CTI_BURST_INC)
        self.comb += [
            self.dma_wb.bte.eq(0),
            self.dma_wb.dat_w.eq(Mux(req_en_sig, out_pack_rd.dat_r, out_rd_port.dat_r)),
            Case(
                dma_state,
                {
                    _DMA_ACT_BURST: [
                        self.dma_wb.cyc.eq(1),
                        self.dma_wb.stb.eq(1),
                        self.dma_wb.we.eq(0),
                        self.dma_wb.sel.eq(0xF),
                        self.dma_wb.adr.eq(cur_act_waddr),
                        self.dma_wb.cti.eq(burst_cti),
                    ],
                    _DMA_SCALE_BURST: [
                        self.dma_wb.cyc.eq(1),
                        self.dma_wb.stb.eq(1),
                        self.dma_wb.we.eq(0),
                        self.dma_wb.sel.eq(0xF),
                        self.dma_wb.adr.eq(cur_scale_waddr),
                        self.dma_wb.cti.eq(burst_cti),
                    ],
                    _DMA_TRIT_BURST: [
                        self.dma_wb.cyc.eq(1),
                        self.dma_wb.stb.eq(1),
                        self.dma_wb.we.eq(0),
                        self.dma_wb.sel.eq(0xF),
                        self.dma_wb.adr.eq(cur_trit_waddr),
                        self.dma_wb.cti.eq(burst_cti),
                    ],
                    _DMA_OUT_WRITE_WB: [
                        self.dma_wb.cyc.eq(1),
                        self.dma_wb.stb.eq(1),
                        self.dma_wb.we.eq(1),
                        self.dma_wb.sel.eq(out_wb_sel),
                        self.dma_wb.adr.eq(cur_out_waddr),
                        self.dma_wb.cti.eq(_CTI_CLASSIC),
                    ],
                    "default": [
                        self.dma_wb.cyc.eq(0),
                        self.dma_wb.stb.eq(0),
                        self.dma_wb.we.eq(0),
                        self.dma_wb.sel.eq(0xF),
                        self.dma_wb.adr.eq(0),
                        self.dma_wb.cti.eq(_CTI_CLASSIC),
                    ],
                },
            ),
        ]

        # Output BRAM Read Port Mux (prefetch idx 0 in WAIT_COMPUTE; 2-cyc writes)
        next_out_rd_adr = Mux(dma_ack, dma_out_idx + 1, dma_out_idx)
        self.comb += [
            If(
                dma_state == _DMA_WAIT_COMPUTE,
                out_rd_port.adr.eq(0),
                out_pack_rd.adr.eq(0),
            )
            .Elif(
                dma_state == _DMA_OUT_WRITE_WB,
                out_rd_port.adr.eq(next_out_rd_adr),
                out_pack_rd.adr.eq(next_out_rd_adr),
            )
            .Else(
                out_rd_port.adr.eq(self.out_row_idx.storage),
                out_pack_rd.adr.eq(0),
            ),
            self.out_row_data.status.eq(out_rd_port.dat_r),
        ]

        # Scale & Trit FIFO Write / Read Wiring into WeightUnpacker
        if self.words_per_beat == 1:
            dma_live_beat = self.dma_wb.dat_r[0:beat_bits]
            beat_complete = Signal(reset=1)
            self.comb += beat_complete.eq(1)
        else:
            dma_live_beat = Cat(
                *[
                    Mux(trit_sub_idx == w, self.dma_wb.dat_r, trit_pack_words[w])
                    for w in range(self.words_per_beat)
                ]
            )
            beat_complete = Signal(name="beat_complete")
            self.comb += beat_complete.eq(trit_sub_idx == (self.words_per_beat - 1))

        is_trit_row_last = Signal(name="is_trit_row_last")
        dma_scale_valid = Signal(name="dma_scale_valid")
        dma_scale_data = Signal(16, name="dma_scale_data")
        scale_word_done = Signal(name="scale_word_done")

        self.comb += [
            is_trit_row_last.eq(trit_row_word_idx == (latched_trit_w_per_row - 1)),
            scale_fifo.din.eq(self.dma_wb.dat_r),
            scale_fifo.we.eq((dma_state == _DMA_SCALE_BURST) & dma_ack),
            trit_fifo.din.eq(Cat(dma_live_beat, is_trit_row_last)),
            trit_fifo.we.eq((dma_state == _DMA_TRIT_BURST) & dma_ack & beat_complete),
            dma_scale_valid.eq(scale_fifo.readable & (scale_emitted_cnt < latched_scale_u16_total)),
            dma_scale_data.eq(Mux(scale_half_idx, scale_fifo.dout[16:32], scale_fifo.dout[0:16])),
            scale_word_done.eq(
                scale_half_idx | ((scale_emitted_cnt + 1) >= latched_scale_u16_total)
            ),
            scale_fifo.re.eq(
                weight_dma_active & dma_scale_valid & self.unpacker.scale_ready & scale_word_done
            ),
            trit_fifo.re.eq(weight_dma_active & self.unpacker.trit_ready),
            If(
                weight_dma_active,
                self.unpacker.trit_data.eq(trit_fifo.dout[0:beat_bits]),
                self.unpacker.trit_last.eq(trit_fifo.dout[beat_bits]),
                self.unpacker.trit_valid.eq(trit_fifo.readable),
                self.trit_ready.eq(0),
                self.unpacker.scale_data.eq(dma_scale_data),
                self.unpacker.scale_valid.eq(dma_scale_valid),
                self.scale_ready.eq(0),
            ).Else(
                self.unpacker.trit_data.eq(self.trit_data),
                self.unpacker.trit_last.eq(self.trit_last),
                self.unpacker.trit_valid.eq(self.trit_valid),
                self.trit_ready.eq(self.unpacker.trit_ready),
                self.unpacker.scale_data.eq(self.scale_data),
                self.unpacker.scale_valid.eq(self.scale_valid),
                self.scale_ready.eq(self.unpacker.scale_ready),
            ),
        ]

        # -------------------------------------------------------------------
        # Activation Staging (CSR Push, Sync-BRAM Loader, and DMA_ACT_BURST)
        # -------------------------------------------------------------------
        act_wr_ptr = Signal(max=act_mem_depth, name="act_wr_ptr")
        stage_words = Array([Signal(32, name=f"stage_w_{w}") for w in range(self.words_per_slice)])
        loading_acts = Signal(name="loading_acts")
        load_word_limit = Signal(17, name="load_word_limit")
        ld_req_idx = Signal(17, name="ld_req_idx")
        ld_issue_en = Signal(name="ld_issue_en")
        ld_resp_valid = Signal(name="ld_resp_valid")
        ld_resp_idx = Signal(17, name="ld_resp_idx")

        csr_sub_idx = Signal(max=max(self.words_per_slice, 2), name="csr_sub_idx")
        csr_slice_idx = Signal(max=max(self.max_beats, 2), name="csr_slice_idx")
        ld_sub_idx = Signal(max=max(self.words_per_slice, 2), name="ld_sub_idx")
        ld_slice_idx = Signal(max=max(self.max_beats, 2), name="ld_slice_idx")
        dma_act_sub_idx = Signal(max=max(self.words_per_slice, 2), name="dma_act_sub_idx")
        dma_act_slice_idx = Signal(max=max(self.max_beats, 2), name="dma_act_slice_idx")

        if wps_shift == 0:
            self.comb += [
                csr_sub_idx.eq(0),
                csr_slice_idx.eq(act_wr_ptr),
                ld_sub_idx.eq(0),
                ld_slice_idx.eq(ld_resp_idx),
                dma_act_sub_idx.eq(0),
                dma_act_slice_idx.eq(dma_act_idx),
            ]
        else:
            self.comb += [
                csr_sub_idx.eq(act_wr_ptr[0:wps_shift]),
                csr_slice_idx.eq(act_wr_ptr[wps_shift:]),
                ld_sub_idx.eq(ld_resp_idx[0:wps_shift]),
                ld_slice_idx.eq(ld_resp_idx[wps_shift:]),
                dma_act_sub_idx.eq(dma_act_idx[0:wps_shift]),
                dma_act_slice_idx.eq(dma_act_idx[wps_shift:]),
            ]

        csr_live_slice = Cat(
            *[
                Mux(csr_sub_idx == w, self.act_word_data.storage, stage_words[w])
                for w in range(self.words_per_slice)
            ]
        )
        ld_live_slice = Cat(
            *[
                Mux(ld_sub_idx == w, act_rd_port.dat_r, stage_words[w])
                for w in range(self.words_per_slice)
            ]
        )
        dma_act_live_slice = Cat(
            *[
                Mux(dma_act_sub_idx == w, self.dma_wb.dat_r, stage_words[w])
                for w in range(self.words_per_slice)
            ]
        )

        dma_act_fire = Signal(name="dma_act_fire")
        self.comb += [
            dma_act_fire.eq((dma_state == _DMA_ACT_BURST) & dma_ack),
            If(
                dma_act_fire,
                act_wr_port.adr.eq(dma_act_idx),
                act_wr_port.dat_w.eq(self.dma_wb.dat_r),
                act_wr_port.we.eq(1),
            ).Else(
                act_wr_port.adr.eq(act_wr_ptr),
                act_wr_port.dat_w.eq(self.act_word_data.storage),
                act_wr_port.we.eq(self.act_word_data.re),
            ),
            ld_issue_en.eq(loading_acts & (~act_dma_active) & (ld_req_idx < load_word_limit)),
            act_rd_port.adr.eq(ld_req_idx),
            If(
                dma_act_fire,
                self.tile.act_wr_addr.eq(dma_act_slice_idx),
                self.tile.act_wr_data.eq(dma_act_live_slice),
                self.tile.act_wr_en.eq(dma_act_sub_idx == (self.words_per_slice - 1)),
            )
            .Elif(
                ld_resp_valid,
                self.tile.act_wr_addr.eq(ld_slice_idx),
                self.tile.act_wr_data.eq(ld_live_slice),
                self.tile.act_wr_en.eq(ld_sub_idx == (self.words_per_slice - 1)),
            )
            .Else(
                self.tile.act_wr_addr.eq(csr_slice_idx),
                self.tile.act_wr_data.eq(csr_live_slice),
                self.tile.act_wr_en.eq(
                    self.act_word_data.re & (csr_sub_idx == (self.words_per_slice - 1))
                ),
            ),
        ]

        # -------------------------------------------------------------------
        # Row-Major Stream -> R-Row Lockstep TernaryTile Feeder
        # -------------------------------------------------------------------
        stripe_base_row = Signal(16, name="stripe_base_row")
        stripe_row_off = Signal(max=max(rows, 2), name="stripe_row_off")
        wr_slice_idx = Signal(max=stripe_mem_depth, name="wr_slice_idx")
        rd_slice_idx = Signal(max=stripe_mem_depth, name="rd_slice_idx")

        rem_in_rows = Signal(17, name="rem_in_rows")
        stripe_target_rows = Signal(max=rows + 1, name="stripe_target_rows")
        in_rows_active = Signal(name="in_rows_active")
        can_accept_u = Signal(name="can_accept_u")
        u_fire = Signal(name="u_fire")

        self.comb += [
            If(
                num_rows_sig > stripe_base_row,
                rem_in_rows.eq(num_rows_sig - stripe_base_row),
            ).Else(
                rem_in_rows.eq(0),
            ),
            If(
                rem_in_rows >= rows,
                stripe_target_rows.eq(rows),
            ).Else(
                stripe_target_rows.eq(rem_in_rows),
            ),
            in_rows_active.eq(stripe_target_rows != 0),
            can_accept_u.eq(enable_sig & (~err_sticky) & (~loading_acts) & in_rows_active),
            u_fire.eq(self.unpacker.out_valid & self.unpacker.out_ready),
            self.tile.clear.eq(clear_sig | start_sig),
            self.tile.shift.eq(shift_sig),
            self.tile.num_rows.eq(Mux(err_sticky, 0, num_rows_sig)),
        ]

        align_valid = Signal(name="align_valid")
        align_trits = Signal(2 * lanes, name="align_trits")
        align_scale = Signal(16, name="align_scale")
        align_last = Signal(name="align_last")
        align_s_rows = Signal(max=rows + 1, name="align_s_rows")
        is_flush_row = Signal(name="is_flush_row")
        align_ready = Signal(name="align_ready")

        if rows == 1:
            self.comb += [
                self.unpacker.out_ready.eq(can_accept_u & self.tile.sink.ready),
                self.tile.sink.valid.eq(self.unpacker.out_valid & can_accept_u),
                self.tile.sink.trits.eq(self.unpacker.trits_packed),
                self.tile.sink.scales.eq(self.unpacker.scale_u16),
                self.tile.sink.last.eq(self.unpacker.row_last),
            ]
        else:
            self.comb += [
                is_flush_row.eq(stripe_row_off == (stripe_target_rows - 1)),
                align_ready.eq((~align_valid) | self.tile.sink.ready),
                If(
                    ~can_accept_u,
                    self.unpacker.out_ready.eq(0),
                )
                .Elif(
                    is_flush_row,
                    self.unpacker.out_ready.eq(align_ready),
                )
                .Else(
                    self.unpacker.out_ready.eq(1),
                ),
            ]

            packed_entry = Cat(self.unpacker.trits_packed, self.unpacker.scale_u16)
            for b in range(rows - 1):
                self.comb += [
                    sw_ports[b].adr.eq(wr_slice_idx),
                    sw_ports[b].dat_w.eq(packed_entry),
                    sw_ports[b].we.eq(u_fire & (~is_flush_row) & (stripe_row_off == b)),
                    sr_ports[b].adr.eq(rd_slice_idx),
                    sr_ports[b].re.eq(u_fire & is_flush_row),
                ]

            row_trit_sigs: list[Signal] = []
            row_scale_sigs: list[Signal] = []
            t_bits = 2 * lanes
            for r in range(rows):
                rt = Signal(t_bits, name=f"mux_rt_{r}")
                rs = Signal(16, name=f"mux_rs_{r}")
                if r < rows - 1:
                    bank_t = sr_ports[r].dat_r[0:t_bits]
                    bank_s = sr_ports[r].dat_r[t_bits:stripe_entry_bits]
                    self.comb += [
                        If(
                            align_s_rows == (r + 1),
                            rt.eq(align_trits),
                            rs.eq(align_scale),
                        )
                        .Elif(
                            align_s_rows > (r + 1),
                            rt.eq(bank_t),
                            rs.eq(bank_s),
                        )
                        .Else(
                            rt.eq(0),
                            rs.eq(0),
                        )
                    ]
                else:
                    self.comb += [
                        If(
                            align_s_rows == rows,
                            rt.eq(align_trits),
                            rs.eq(align_scale),
                        ).Else(
                            rt.eq(0),
                            rs.eq(0),
                        )
                    ]
                row_trit_sigs.append(rt)
                row_scale_sigs.append(rs)

            self.comb += [
                self.tile.sink.valid.eq(align_valid),
                self.tile.sink.last.eq(align_last),
                self.tile.sink.trits.eq(Cat(*row_trit_sigs)),
                self.tile.sink.scales.eq(Cat(*row_scale_sigs)),
            ]

        # -------------------------------------------------------------------
        # Output Routing: Wide int32 Scratchpad + Packed int8 Coalescer (3.2b)
        # -------------------------------------------------------------------
        req_i8_signed = Signal((8, True), name="req_i8_signed")
        req_ext_48 = Signal((acc_bits, True), name="req_ext_48")
        tile_raw_48 = Signal((acc_bits, True), name="tile_raw_48")

        out_commit_valid = Signal(name="out_commit_valid")
        out_commit_row = Signal(16, name="out_commit_row")
        out_commit_val48 = Signal((acc_bits, True), name="out_commit_val48")
        out_commit_sat = Signal(name="out_commit_sat")

        self.comb += [
            self.requantize.clear.eq(clear_sig | start_sig),
            self.requantize.scale_u16.eq(self.req_cfg.fields.scale_u16),
            self.requantize.shift.eq(self.req_cfg.fields.shift),
            self.requantize.symmetric.eq(req_sym_sig),
            self.requantize.sink.result.eq(self.tile.source.result),
            self.requantize.sink.row_idx.eq(self.tile.source.row_idx),
            self.requantize.sink.last.eq(self.tile.source.last),
            self.requantize.source.ready.eq(1),
            req_i8_signed.eq(self.requantize.source.result),
            req_ext_48.eq(req_i8_signed),
            tile_raw_48.eq(self.tile.source.result),
            If(
                req_en_sig,
                self.requantize.sink.valid.eq(self.tile.source.valid),
                self.tile.source.ready.eq(self.requantize.sink.ready),
                out_commit_valid.eq(self.requantize.source.valid),
                out_commit_row.eq(self.requantize.source.row_idx),
                out_commit_val48.eq(req_ext_48),
                out_commit_sat.eq(self.requantize.source.saturated),
            ).Else(
                self.requantize.sink.valid.eq(0),
                self.tile.source.ready.eq(1),
                out_commit_valid.eq(self.tile.source.valid),
                out_commit_row.eq(self.tile.source.row_idx),
                out_commit_val48.eq(tile_raw_48),
                out_commit_sat.eq(0),
            ),
            out_wr_port.adr.eq(out_commit_row),
            out_wr_port.dat_w.eq(out_commit_val48[0:32]),
            out_wr_port.we.eq(out_commit_valid & (out_commit_row < self.max_rows)),
        ]

        # Coalesce 4 consecutive int8 row results into 32-bit LE words for req_enable == 1
        pack_bytes = Array([Signal(8, name=f"out_pb_{k}") for k in range(3)])
        pack_sub_k = Signal(2, name="pack_sub_k")
        pack_word_idx = Signal(16, name="pack_word_idx")
        cur_i8_u8 = Signal(8, name="cur_i8_u8")
        pack_is_last_row = Signal(name="pack_is_last_row")
        pack_flush = Signal(name="pack_flush")
        pack_live_u32 = Signal(32, name="pack_live_u32")

        pb0 = Mux(pack_sub_k == 0, cur_i8_u8, pack_bytes[0])
        pb1 = Mux(pack_sub_k == 1, cur_i8_u8, Mux(pack_sub_k < 1, 0, pack_bytes[1]))
        pb2 = Mux(pack_sub_k == 2, cur_i8_u8, Mux(pack_sub_k < 2, 0, pack_bytes[2]))
        pb3 = Mux(pack_sub_k == 3, cur_i8_u8, 0)

        self.comb += [
            pack_sub_k.eq(out_commit_row[0:2]),
            pack_word_idx.eq(out_commit_row[2:16]),
            cur_i8_u8.eq(out_commit_val48[0:8]),
            pack_is_last_row.eq((out_commit_row + 1) >= num_rows_sig),
            pack_flush.eq((pack_sub_k == 3) | pack_is_last_row),
            pack_live_u32.eq(Cat(pb0, pb1, pb2, pb3)),
            out_pack_wr.adr.eq(pack_word_idx),
            out_pack_wr.dat_w.eq(pack_live_u32),
            out_pack_wr.we.eq(
                out_commit_valid & req_en_sig & pack_flush & (pack_word_idx < out_pack_depth)
            ),
        ]

        # Status & Performance CSR wiring
        busy_wire = Signal(name="busy_wire")
        done_wire = Signal(name="done_wire")
        upper_signed = Signal((16, True), name="upper_signed")
        upper_i32 = Signal((32, True), name="upper_i32")

        self.comb += [
            done_wire.eq(
                (~err_sticky)
                & (num_rows_sig != 0)
                & (rows_done >= num_rows_sig)
                & ((~out_dma_active) | out_dma_done)
            ),
            busy_wire.eq(
                (~err_sticky)
                & (
                    loading_acts
                    | (dma_state != _DMA_IDLE)
                    | ((num_rows_sig != 0) & (rows_done < num_rows_sig))
                    | (out_dma_active & (~out_dma_done))
                )
            ),
            upper_signed.eq(last_res[32:48]),
            upper_i32.eq(upper_signed),
            self.result_lo.status.eq(last_res[0:32]),
            self.result_hi.status.eq(upper_i32),
            self.status.fields.busy.eq(busy_wire),
            self.status.fields.done.eq(done_wire),
            self.status.fields.trit_ready.eq(self.trit_ready),
            self.status.fields.scale_ready.eq(self.scale_ready),
            self.status.fields.error.eq(err_sticky),
            self.status.fields.req_saturated.eq(req_sat_sticky),
            self.status.fields.err_code.eq(err_code_reg),
            self.status.fields.rows_completed.eq(rows_done),
            self.perf_cycles.status.eq(perf_cycles_cnt),
            self.perf_bus_beats.status.eq(perf_beats_cnt),
            self.perf_sat_rows.status.eq(perf_sat_cnt),
        ]

        # -------------------------------------------------------------------
        # Sequential State Updates
        # -------------------------------------------------------------------
        stage_csr_stmts = [
            If(csr_sub_idx == w, stage_words[w].eq(self.act_word_data.storage))
            for w in range(self.words_per_slice)
        ]
        stage_ld_stmts = [
            If(ld_sub_idx == w, stage_words[w].eq(act_rd_port.dat_r))
            for w in range(self.words_per_slice)
        ]
        stage_dma_act_stmts = [
            If(dma_act_sub_idx == w, stage_words[w].eq(self.dma_wb.dat_r))
            for w in range(self.words_per_slice)
        ]
        tpack_stmts = [
            If(trit_sub_idx == w, trit_pack_words[w].eq(self.dma_wb.dat_r))
            for w in range(self.words_per_beat)
        ]

        next_scale_burst = Mux(dma_scale_words_rem > 32, 32, dma_scale_words_rem[0:17])
        next_trit_burst = Mux(dma_trit_words_rem > 64, 64, dma_trit_words_rem[0:17])

        stripe_sync_stmts = []
        if rows == 1:
            stripe_sync_stmts.append(
                If(
                    u_fire & self.unpacker.row_last,
                    stripe_base_row.eq(stripe_base_row + 1),
                )
            )
        else:
            stripe_sync_stmts.extend(
                [
                    If(
                        u_fire & (~is_flush_row),
                        If(
                            self.unpacker.row_last | (wr_slice_idx == (stripe_mem_depth - 1)),
                            wr_slice_idx.eq(0),
                            stripe_row_off.eq(stripe_row_off + 1),
                        ).Else(
                            wr_slice_idx.eq(wr_slice_idx + 1),
                        ),
                    ),
                    If(
                        align_ready,
                        If(
                            u_fire & is_flush_row,
                            align_valid.eq(1),
                            align_trits.eq(self.unpacker.trits_packed),
                            align_scale.eq(self.unpacker.scale_u16),
                            align_last.eq(self.unpacker.row_last),
                            align_s_rows.eq(stripe_target_rows),
                            If(
                                self.unpacker.row_last | (rd_slice_idx == (stripe_mem_depth - 1)),
                                rd_slice_idx.eq(0),
                                stripe_row_off.eq(0),
                                stripe_base_row.eq(stripe_base_row + rows),
                            ).Else(
                                rd_slice_idx.eq(rd_slice_idx + 1),
                            ),
                        ).Else(
                            align_valid.eq(0),
                        ),
                    ),
                ]
            )

        self.sync += [
            If(
                self.act_word_idx.re,
                act_wr_ptr.eq(self.act_word_idx.storage),
            )
            .Elif(
                dma_act_fire,
                *stage_dma_act_stmts,
            )
            .Elif(
                self.act_word_data.re,
                *stage_csr_stmts,
                If(
                    act_wr_ptr == (self.total_act_words - 1),
                    act_wr_ptr.eq(0),
                ).Else(
                    act_wr_ptr.eq(act_wr_ptr + 1),
                ),
            )
            .Elif(
                ld_resp_valid,
                *stage_ld_stmts,
            ),
            If(
                clear_sig,
                err_sticky.eq(0),
                err_code_reg.eq(0),
                req_sat_sticky.eq(0),
                rows_done.eq(0),
                last_res.eq(0),
                perf_cycles_cnt.eq(0),
                perf_beats_cnt.eq(0),
                perf_sat_cnt.eq(0),
                loading_acts.eq(0),
                ld_req_idx.eq(0),
                ld_resp_valid.eq(0),
                stripe_base_row.eq(0),
                stripe_row_off.eq(0),
                wr_slice_idx.eq(0),
                rd_slice_idx.eq(0),
                align_valid.eq(0),
                dma_state.eq(_DMA_IDLE),
                weight_dma_active.eq(0),
                act_dma_active.eq(0),
                out_dma_active.eq(0),
                out_dma_done.eq(0),
                scale_emitted_cnt.eq(0),
                scale_half_idx.eq(0),
                trit_sub_idx.eq(0),
                trit_row_word_idx.eq(0),
                pack_bytes[0].eq(0),
                pack_bytes[1].eq(0),
                pack_bytes[2].eq(0),
            )
            .Elif(
                start_sig,
                req_sat_sticky.eq(0),
                rows_done.eq(0),
                last_res.eq(0),
                perf_cycles_cnt.eq(0),
                perf_beats_cnt.eq(0),
                perf_sat_cnt.eq(0),
                stripe_base_row.eq(0),
                stripe_row_off.eq(0),
                wr_slice_idx.eq(0),
                rd_slice_idx.eq(0),
                align_valid.eq(0),
                ld_req_idx.eq(0),
                ld_resp_valid.eq(0),
                dma_act_idx.eq(0),
                dma_out_idx.eq(0),
                scale_emitted_cnt.eq(0),
                scale_half_idx.eq(0),
                trit_sub_idx.eq(0),
                trit_row_word_idx.eq(0),
                pack_bytes[0].eq(0),
                pack_bytes[1].eq(0),
                pack_bytes[2].eq(0),
                If(
                    start_err_mask != 0,
                    err_sticky.eq(1),
                    err_code_reg.eq(start_err_mask),
                    loading_acts.eq(0),
                    dma_state.eq(_DMA_IDLE),
                    weight_dma_active.eq(0),
                    act_dma_active.eq(0),
                    out_dma_active.eq(0),
                    out_dma_done.eq(0),
                ).Else(
                    err_sticky.eq(0),
                    err_code_reg.eq(0),
                    loading_acts.eq(1),
                    load_word_limit.eq(target_load_words),
                    weight_dma_active.eq(self.weight_addr.storage != 0),
                    act_dma_active.eq(self.act_addr.storage != 0),
                    out_dma_active.eq(self.out_addr.storage != 0),
                    out_dma_done.eq(self.out_addr.storage == 0),
                    cur_act_waddr.eq(self.act_addr.storage[2:32]),
                    cur_scale_waddr.eq(self.scale_addr.storage[2:32]),
                    cur_trit_waddr.eq(self.weight_addr.storage[2:32]),
                    cur_out_waddr.eq(self.out_addr.storage[2:32]),
                    dma_scale_words_rem.eq(scale_total_words_wire),
                    dma_trit_words_rem.eq(trit_total_words_wire),
                    latched_trit_w_per_row.eq(trit_w_per_row_wire),
                    latched_scale_u16_total.eq(scale_total_u16_wire),
                    If(
                        self.act_addr.storage != 0,
                        burst_rem.eq(target_load_words),
                        dma_state.eq(_DMA_ACT_BURST),
                    )
                    .Elif(
                        self.weight_addr.storage != 0,
                        dma_state.eq(_DMA_STREAM_ARB),
                    )
                    .Elif(
                        self.out_addr.storage != 0,
                        dma_state.eq(_DMA_WAIT_COMPUTE),
                    )
                    .Else(
                        dma_state.eq(_DMA_IDLE),
                    ),
                ),
            )
            .Else(
                # 1-cycle synchronous BRAM activation loader FSM (when act_addr == 0)
                ld_resp_valid.eq(ld_issue_en),
                ld_resp_idx.eq(ld_req_idx),
                If(ld_issue_en, ld_req_idx.eq(ld_req_idx + 1)),
                If(
                    loading_acts
                    & (~act_dma_active)
                    & ld_resp_valid
                    & ((ld_resp_idx + 1) >= load_word_limit),
                    loading_acts.eq(0),
                ),
                # Scale u16 half-word unpacker
                If(
                    weight_dma_active & dma_scale_valid & self.unpacker.scale_ready,
                    scale_emitted_cnt.eq(scale_emitted_cnt + 1),
                    If(scale_word_done, scale_half_idx.eq(0)).Else(scale_half_idx.eq(1)),
                ),
                # Wishbone Burst DMA FSM
                Case(
                    dma_state,
                    {
                        _DMA_ACT_BURST: [
                            If(
                                dma_ack,
                                cur_act_waddr.eq(cur_act_waddr + 1),
                                dma_act_idx.eq(dma_act_idx + 1),
                                If(
                                    burst_rem == 1,
                                    loading_acts.eq(0),
                                    If(
                                        weight_dma_active,
                                        dma_state.eq(_DMA_STREAM_ARB),
                                    )
                                    .Elif(
                                        out_dma_active,
                                        dma_state.eq(_DMA_WAIT_COMPUTE),
                                    )
                                    .Else(
                                        dma_state.eq(_DMA_IDLE),
                                    ),
                                ).Else(
                                    burst_rem.eq(burst_rem - 1),
                                ),
                            )
                        ],
                        _DMA_STREAM_ARB: [
                            If(
                                (dma_scale_words_rem != 0) & (scale_fifo.level <= 28),
                                burst_rem.eq(next_scale_burst),
                                dma_state.eq(_DMA_SCALE_BURST),
                            )
                            .Elif(
                                (dma_trit_words_rem != 0) & (trit_fifo.level <= 4),
                                burst_rem.eq(next_trit_burst),
                                dma_state.eq(_DMA_TRIT_BURST),
                            )
                            .Elif(
                                (dma_scale_words_rem == 0) & (dma_trit_words_rem == 0),
                                dma_state.eq(_DMA_WAIT_COMPUTE),
                            )
                        ],
                        _DMA_SCALE_BURST: [
                            If(
                                dma_ack,
                                cur_scale_waddr.eq(cur_scale_waddr + 1),
                                dma_scale_words_rem.eq(dma_scale_words_rem - 1),
                                If(
                                    burst_rem == 1,
                                    dma_state.eq(_DMA_STREAM_ARB),
                                ).Else(
                                    burst_rem.eq(burst_rem - 1),
                                ),
                            )
                        ],
                        _DMA_TRIT_BURST: [
                            If(
                                dma_ack,
                                *tpack_stmts,
                                If(beat_complete, trit_sub_idx.eq(0)).Else(
                                    trit_sub_idx.eq(trit_sub_idx + 1)
                                ),
                                If(is_trit_row_last, trit_row_word_idx.eq(0)).Else(
                                    trit_row_word_idx.eq(trit_row_word_idx + 1)
                                ),
                                cur_trit_waddr.eq(cur_trit_waddr + 1),
                                dma_trit_words_rem.eq(dma_trit_words_rem - 1),
                                If(
                                    burst_rem == 1,
                                    dma_state.eq(_DMA_STREAM_ARB),
                                ).Else(
                                    burst_rem.eq(burst_rem - 1),
                                ),
                            )
                        ],
                        _DMA_WAIT_COMPUTE: [
                            If(
                                rows_done >= num_rows_sig,
                                If(
                                    out_dma_active,
                                    dma_out_idx.eq(0),
                                    dma_state.eq(_DMA_OUT_WRITE_WB),
                                ).Else(
                                    out_dma_done.eq(1),
                                    dma_state.eq(_DMA_IDLE),
                                ),
                            )
                        ],
                        _DMA_OUT_WRITE_WB: [
                            If(
                                dma_ack,
                                If(
                                    is_final_out_beat,
                                    out_dma_done.eq(1),
                                    dma_state.eq(_DMA_IDLE),
                                ).Else(
                                    dma_out_idx.eq(dma_out_idx + 1),
                                    cur_out_waddr.eq(cur_out_waddr + 1),
                                ),
                            )
                        ],
                    },
                ),
                # Telemetry counters
                If(busy_wire, perf_cycles_cnt.eq(perf_cycles_cnt + 1)),
                If(
                    Mux(any_dma_run, dma_ack, self.trit_valid & self.trit_ready),
                    perf_beats_cnt.eq(perf_beats_cnt + 1),
                ),
                *stripe_sync_stmts,
                If(
                    out_commit_valid,
                    last_res.eq(out_commit_val48),
                    rows_done.eq(rows_done + 1),
                    If(
                        req_en_sig,
                        If(pack_sub_k == 0, pack_bytes[0].eq(cur_i8_u8)),
                        If(pack_sub_k == 1, pack_bytes[1].eq(cur_i8_u8)),
                        If(pack_sub_k == 2, pack_bytes[2].eq(cur_i8_u8)),
                    ),
                    If(
                        out_commit_sat,
                        req_sat_sticky.eq(1),
                        perf_sat_cnt.eq(perf_sat_cnt + 1),
                    ),
                ),
            ),
        ]


def export_soc_csr_artifacts(
    json_path: Path | None = DEFAULT_CSR_JSON,
    header_path: Path | None = DEFAULT_CSR_HEADER,
    *,
    check: bool = False,
) -> tuple[str, str]:
    """Deterministically generate (or verify) SetunSimSoC `csr.json` and `csr.h`."""
    from targets.sim import SetunSimSoC

    soc = SetunSimSoC(
        with_accel_stub=True,
        with_ternary_accel=True,
        use_external_crg=True,
        ident_version=False,
        cpu_type=None,
        integrated_rom_size=0,
        integrated_main_ram_size=0x400000,
    )
    soc.finalize()

    raw_json = export.get_csr_json(
        soc=soc,
        csr_regions=soc.csr.regions,
        constants=soc.constants,
        mem_regions=soc.mem_regions,
    )
    json_text = raw_json.replace("\r\n", "\n").rstrip("\n") + "\n"

    raw_header = export.get_csr_header(
        regions=soc.csr.regions,
        constants=soc.constants,
        csr_ordering=soc.csr.ordering,
        csr_base=soc.mem_regions["csr"].origin,
        cpu=soc.cpu,
        with_access_functions=True,
        with_fields_access_functions=True,
    )
    normalized_header = re.sub(
        r"\A//-{80}\n// Auto-generated by LiteX .*?\n//-{80}",
        _DETERMINISTIC_BANNER,
        raw_header.replace("\r\n", "\n"),
        count=1,
    )
    header_text = normalized_header.rstrip("\n") + "\n"

    if check:
        if json_path is not None:
            if not json_path.exists() or json_path.read_text(encoding="utf-8") != json_text:
                raise RuntimeError(
                    f"[setun/soc/ternary_accel.py:export_soc_csr_artifacts] deterministic CSR "
                    f"invariant violated: '{json_path}' is missing or out of sync."
                )
        if header_path is not None:
            if not header_path.exists() or header_path.read_text(encoding="utf-8") != header_text:
                raise RuntimeError(
                    f"[setun/soc/ternary_accel.py:export_soc_csr_artifacts] deterministic CSR "
                    f"invariant violated: '{header_path}' is missing or out of sync."
                )
        return json_text, header_text

    if json_path is not None:
        json_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.write_text(json_text, encoding="utf-8")
    if header_path is not None:
        header_path.parent.mkdir(parents=True, exist_ok=True)
        header_path.write_text(header_text, encoding="utf-8")

    return json_text, header_text
